#!/bin/bash

# Deploy script for Assignment 1 - Infrastructure
set -e

# Check if we're in the right directory
if [ ! -f "deploy.sh" ] || [ ! -d "deploy/terraform" ]; then
    echo "Error: Please run this script from the project root directory"
    echo "   Example: cd assignment-1-infrastructure && ./deploy.sh"
    exit 1
fi

echo "Starting Assignment 1 Infrastructure Deployment..."

# Load environment variables if .env exists
if [ -f .env ]; then
    echo "Loading environment variables from .env..."
    source .env
else
    echo "Warning: No .env file found. Using system environment variables."
fi

# Check if required tools are installed
echo "Checking required tools..."
command -v terraform >/dev/null 2>&1 || { echo "Error: Terraform not found."; exit 1; }
command -v ansible-playbook >/dev/null 2>&1 || { echo "Error: Ansible not found."; exit 1; }

# Check directory structure
echo "Checking project structure..."
if [ ! -d "deploy/terraform" ] || [ ! -d "deploy/ansible" ]; then
    echo "Error: Required directories not found!"
    exit 1
fi

# Step 1: Initialize and apply Terraform
echo "Step 1: Creating infrastructure with Terraform..."
cd deploy/terraform

if [ ! -d ".terraform" ]; then
    terraform init
fi

terraform plan
terraform apply -auto-approve

# Step 2: Extract outputs from Terraform
echo "Step 2: Getting server IP addresses..."
LB_PUBLIC_IP=$(terraform output -raw loadbalancer_public_ip)
LB_PRIVATE_IP=$(terraform output -raw loadbalancer_private_ip)
LB_PORT=$(terraform output -raw loadbalancer_port)
WS1_PRIVATE_IP=$(terraform output -raw webserver1_private_ip)
WS2_PRIVATE_IP=$(terraform output -raw webserver2_private_ip)

echo "Server IP addresses:"
echo "   Load Balancer Public:  $LB_PUBLIC_IP"
echo "   Load Balancer Private: $LB_PRIVATE_IP"
echo "   Webserver 1 Private:   $WS1_PRIVATE_IP"
echo "   Webserver 2 Private:   $WS2_PRIVATE_IP"

# Terraform has already created inventory-generated via templatefile()
echo "Ansible inventory automatically generated by Terraform!"

# Go back to root directory
cd ../../

# Step 3: Wait for SSH on load balancer
echo "Step 3: Waiting for SSH on load balancer..."
max_attempts=30
attempt=1

while [ $attempt -le $max_attempts ]; do
    if ssh -i $TF_VAR_identity_file -o ConnectTimeout=5 -o StrictHostKeyChecking=no ubuntu@$LB_PUBLIC_IP "echo 'SSH Ready'" >/dev/null 2>&1; then
        echo "Load balancer SSH ready!"
        break
    else
        echo "   Attempt $attempt/$max_attempts..."
        sleep 10
        ((attempt++))
    fi
done

# Step 3b: Wait a bit more for webservers to fully boot
echo "Step 3b: Waiting for webservers to respond..."
max_attempts=30
attempt=1

while [ $attempt -le $max_attempts ]; do
    if ssh -i $TF_VAR_identity_file \
           -o ProxyJump="ubuntu@$LB_PUBLIC_IP" \
           -o ConnectTimeout=5 \
           -o StrictHostKeyChecking=no \
           ubuntu@$WS1_PRIVATE_IP \
           "echo 'ready'" >/dev/null 2>&1; then
        echo "Webservers are ready!"
        break
    else
        echo "   Waiting for webservers... (attempt $attempt/$max_attempts)"
        sleep 2
        ((attempt++))
    fi
done

# Step 4: Run Ansible playbook
echo "Step 4: Configuring servers with Ansible..."
cd deploy/ansible

ansible-playbook -i inventory-generated playbook.yml

cd ../../

echo "All servers configured successfully!"
echo ""
echo "Deployment Summary:"
echo "Web application is available at: http://$LB_PUBLIC_IP:$LB_PORT" 
echo "SSH access: ssh ubuntu@$LB_PUBLIC_IP"
echo "To destroy: cd deploy/terraform && terraform destroy -auto-approve"
